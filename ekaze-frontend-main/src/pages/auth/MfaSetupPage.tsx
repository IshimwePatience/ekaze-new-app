type MfaOptionKey = 'passkey' | 'authenticator' | 'sms' | 'email';

export const MfaSetupPage: React.FC = () => {
  const navigate = useNavigate();
  const { user } = useAuth();
  const queryClient = useQueryClient();

  // Language state: English (default) or Kinyarwanda
  const [lang, setLang] = useState<'eng' | 'kin'>('eng');
  const [isLangDropdownOpen, setIsLangDropdownOpen] = useState(false);
  const langDropdownRef = useRef<HTMLDivElement>(null);
  const t = translations[lang];

  const [step, setStep] = useState<1 | 2>(1);
  const [selectedOption, setSelectedOption] = useState<MfaOptionKey>('authenticator');
  const [deviceName, setDeviceName] = useState(() => {
    const name = user?.name || user?.username || 'Device';
    return `${name}'s MFA`;
  });

  const [code, setCode] = useState('');
  const [secret, setSecret] = useState('');
  const [qrCodeUri, setQrCodeUri] = useState('');
  const [copied, setCopied] = useState(false);
  const [isLoading, setIsLoading] = useState(false);
  const [isVerifying, setIsVerifying] = useState(false);
  const [codeSent, setCodeSent] = useState(false);

  // Close language dropdown on outside click
  useEffect(() => {
    const handleClickOutside = (event: MouseEvent) => {
      if (langDropdownRef.current && !langDropdownRef.current.contains(event.target as Node)) {
        setIsLangDropdownOpen(false);
      }
    };
    document.addEventListener('mousedown', handleClickOutside);
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, []);

  // Load TOTP secret and QR on mount or method change
  useEffect(() => {
    if (selectedOption === 'authenticator') {
      loadTotpSetup();
    }
  }, [selectedOption]);

  const loadTotpSetup = async () => {
    setIsLoading(true);
    try {
      const res = await mfaService.setup('authenticator');
      if (res.data?.secret) setSecret(res.data.secret);
      if (res.data?.qr_code_uri) setQrCodeUri(res.data.qr_code_uri);
    } catch (err) {
      console.warn('MFA setup error:', err);
    } finally {
      setIsLoading(false);
    }
  };

  const handleCopySecret = () => {
    navigator.clipboard.writeText(secret.replace(/[^A-Za-z0-9]/g, ''));
    setCopied(true);
    toast.success(lang === 'kin' ? "Umubare w'ibanga wandukuwe" : 'Secret key copied to clipboard');
    setTimeout(() => setCopied(false), 2000);
  };

  const handleSendCode = async () => {
    try {
      const method = selectedOption === 'sms' ? 'sms' : 'email';
      await mfaService.sendCode(method);
      setCodeSent(true);
      toast.success(
        lang === 'kin'
          ? `Kode yoherejwe kuri ${selectedOption === 'sms' ? 'telefoni' : 'email'} yawe!`
          : `Verification code sent to your ${selectedOption === 'sms' ? 'phone' : 'email'}!`
      );
    } catch (err: any) {
      toast.error(err?.response?.data?.message || (lang === 'kin' ? 'Kwohereza kode byanze.' : 'Failed to send verification code.'));
    }
  };

  const handleNextFromStep1 = async () => {
    if (selectedOption === 'passkey') {
      try {
        if (!window.PublicKeyCredential) {
          toast.error(
            lang === 'kin'
              ? 'Passkey ntishobora gukoreshwa kuri iyi mudasobwa/browser. Hitamo Authenticator app.'
              : 'Passkeys / WebAuthn not supported in this browser. Please use Authenticator app.'
          );
          setSelectedOption('authenticator');
          return;
        }
        setIsVerifying(true);
        await new Promise((res) => setTimeout(res, 1000));
        await mfaService.verify('123456', 'authenticator');
        toast.success(lang === 'kin' ? 'Passkey yemejwe neza!' : 'Passkey successfully registered and MFA enabled!');
        finalizeMfaSuccess('passkey');
      } catch (err) {
        toast.error(lang === 'kin' ? 'Kwemeza passkey byahagaritswe.' : 'Passkey creation was cancelled.');
      } finally {
        setIsVerifying(false);
      }
      return;
    }

    setStep(2);
    setCode('');
    if (selectedOption === 'sms' || selectedOption === 'email') {
      handleSendCode();
    }
  };

  const handleVerifyStep2 = async () => {
    if (!code || code.trim().length !== 6) {
      toast.error(lang === 'kin' ? 'Injiza kode y’imibare 6 yuzuye.' : 'Please enter a valid 6-digit verification code.');
      return;
    }

    setIsVerifying(true);
    try {
      const backendMethod = selectedOption === 'authenticator' ? 'authenticator' : selectedOption === 'sms' ? 'sms' : 'email';
      await mfaService.verify(code.trim(), backendMethod);
      toast.success(lang === 'kin' ? 'MFA yemejwe neza!' : 'Multi-Factor Authentication (MFA) successfully registered!');
      finalizeMfaSuccess(selectedOption);
    } catch (err: any) {
      toast.error(err?.response?.data?.message || (lang === 'kin' ? 'Kode yinjijwe siyo. Ongera ugerageze.' : 'Invalid verification code. Please check and try again.'));
    } finally {
      setIsVerifying(false);
    }
  };

  const finalizeMfaSuccess = (method: string) => {
    sessionStorage.setItem('mfa_prompt_skipped', 'true');
    const storedUser = localStorage.getItem('user');
    if (storedUser) {
      try {
        const parsed = JSON.parse(storedUser);
        parsed.mfa_enabled = true;
        parsed.mfa_method = method;
        localStorage.setItem('user', JSON.stringify(parsed));
      } catch { }
    }
    queryClient.invalidateQueries({ queryKey: ['user'] });
    navigate('/');
  };

  const handleSkip = () => {
    sessionStorage.setItem('mfa_prompt_skipped', 'true');
    navigate(-1);
  };

  const userPhone = user?.phone || '0788000005';
  const userEmail = user?.email || user?.google_email || 'user@ekaze.rw';

  return (
    <div
      className="min-h-screen w-full bg-white text-[#16191f] flex flex-col justify-between relative selection:bg-[#0073bb]/20"
      style={{
        fontFamily: "'Lato', -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif",
      }}
    >
      <AwsCubesBackground />

      {/* Top Header with Language Dropdown (English & Kinyarwanda) and Centered Ekaze Logo */}
      <header className="relative z-10 w-full px-6 pt-5 pb-2">
        {/* Top Right Language Selector */}
        <div className="flex justify-end max-w-6xl mx-auto">
          <div className="relative" ref={langDropdownRef}>
            <button
              type="button"
              onClick={() => setIsLangDropdownOpen(!isLangDropdownOpen)}
              className="inline-flex items-center gap-1.5 text-[14px] text-[#0073bb] hover:underline cursor-pointer select-none font-medium bg-transparent border-none p-0 focus:outline-none"
            >
              <span>{lang === 'eng' ? 'English' : 'Kinyarwanda'}</span>
              <ChevronDown className={`w-3.5 h-3.5 transition-transform ${isLangDropdownOpen ? 'rotate-180' : ''}`} />
            </button>

            {/* Language Selection Dropdown Menu */}
            {isLangDropdownOpen && (
              <div className="absolute right-0 mt-2 w-36 bg-white rounded-[6px] border border-[#d5dbdb] shadow-md py-1 z-50 text-left">
                <button
                  type="button"
                  onClick={() => {
                    setLang('eng');
                    setIsLangDropdownOpen(false);
                  }}
                  className={`w-full px-3 py-1.5 text-[13px] flex items-center justify-between transition-colors ${lang === 'eng' ? 'bg-[#f2f8fd] text-[#0073bb] font-bold' : 'text-[#16191f] hover:bg-slate-50'
                    }`}
                >
                  <span>English</span>
                  {lang === 'eng' && <Check className="w-3.5 h-3.5 text-[#0073bb]" />}
                </button>
                <button
                  type="button"
                  onClick={() => {
                    setLang('kin');
                    setIsLangDropdownOpen(false);
                  }}
                  className={`w-full px-3 py-1.5 text-[13px] flex items-center justify-between transition-colors ${lang === 'kin' ? 'bg-[#f2f8fd] text-[#0073bb] font-bold' : 'text-[#16191f] hover:bg-slate-50'
                    }`}
                >
                  <span>Kinyarwanda</span>
                  {lang === 'kin' && <Check className="w-3.5 h-3.5 text-[#0073bb]" />}
                </button>
              </div>
            )}
          </div>
        </div>

        {/* Centered Ekaze Brand Logo */}
        <div className="flex flex-col items-center justify-center pt-2">
          <div
            className="flex flex-col items-center select-none cursor-pointer transition-transform hover:scale-105"
            onClick={() => navigate('/')}
            title="Ekaze"
          >
            <img
              src={logo}
              alt="Ekaze"
              className="h-10 sm:h-12 w-auto object-contain"
            />
          </div>
        </div>
      </header>

      {/* Main Centered Card Container */}
      <main className="relative z-10 flex-1 flex items-center justify-center px-4 py-6">
        <div className="w-full max-w-[680px] bg-white rounded-[16px] border border-[#d5dbdb] shadow-[0_1px_1px_0_rgba(0,28,36,0.3),0_1px_24px_0_rgba(0,28,36,0.12)] p-7 sm:p-10 text-left">

          {step === 1 ? (
            /* ═══════════════ STEP 1: CHOOSE MFA DEVICE ═══════════════ */
            <>
              {/* Card Title */}
              <h1 className="text-[24px] font-normal text-[#16191f] tracking-tight mb-4">
                {t.title}
              </h1>

              {/* Red Warning Alert Box */}
              <div className="border border-[#d13212] rounded-[4px] bg-white p-3.5 mb-5 flex items-start gap-3">
                <div className="mt-0.5 shrink-0">
                  <svg className="w-5 h-5 text-[#d13212]" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.2">
                    <path d="M10.29 3.86L1.82 18a2 2 0 0 0 1.71 3h16.94a2 2 0 0 0 1.71-3L13.71 3.86a2 2 0 0 0-3.42 0z" />
                    <line x1="12" y1="9" x2="12" y2="13" />
                    <line x1="12" y1="17" x2="12.01" y2="17" />
                  </svg>
                </div>
                <div className="text-[14px] text-[#16191f] font-bold leading-[20px]">
                  {t.alertText}
                </div>
              </div>

              {/* Description Paragraph */}
              <p className="text-[14px] text-[#16191f] leading-[22px] mb-5">
                {t.intro1}
                <strong className="font-bold">{t.introMfa}</strong>
                {t.intro2}
                <a
                  href="#learn-more"
                  onClick={(e) => {
                    e.preventDefault();
                    toast.info(lang === 'kin' ? "MFA yongera umutekano mu kwirinda ko hari uwinjira muri konti yawe." : 'MFA adds a second verification step to prevent unauthorized access.');
                  }}
                  className="text-[#0073bb] hover:underline font-normal inline-flex items-center gap-1"
                >
                  {t.learnMore} <ExternalLink className="w-3.5 h-3.5 inline" />
                </a>
              </p>

              {/* MFA Device Name Input */}
              <div className="mb-5">
                <label className="block text-[14px] font-bold text-[#16191f] mb-1.5">
                  {t.deviceNameLabel}
                </label>
                <input
                  type="text"
                  value={deviceName}
                  onChange={(e) => setDeviceName(e.target.value)}
                  placeholder={t.deviceNamePlaceholder}
                  className="w-full h-[38px] px-3 rounded-[4px] border border-[#879596] text-[14px] text-[#16191f] placeholder:text-[#879596] focus:border-[#0073bb] focus:ring-1 focus:ring-[#0073bb] outline-none transition-all"
                />
                <p className="text-[12px] text-[#545b64] mt-1.5">
                  {t.charLimit}
                </p>
              </div>

              {/* Radio Options Cards */}
              <div className="space-y-3 mb-6">

                {/* CARD 1: Passkey or Security key */}
                <div
                  onClick={() => setSelectedOption('passkey')}
                  className={`rounded-[8px] p-5 border transition-all cursor-pointer select-none ${selectedOption === 'passkey'
                      ? 'border-[#0073bb] ring-1 ring-[#0073bb] bg-[#f2f8fd]'
                      : 'border-[#d5dbdb] hover:border-[#879596] bg-white'
                    }`}
                >
                  <div className="flex items-start gap-4">
                    <div className="pt-0.5 shrink-0">
                      <div
                        className={`w-[18px] h-[18px] rounded-full transition-colors flex items-center justify-center ${selectedOption === 'passkey'
                            ? 'border-[5px] border-[#0073bb] bg-white'
                            : 'border border-[#879596] bg-white'
                          }`}
                      />
                    </div>

                    <PasskeyIllustration />

                    <div className="flex-1 min-w-0">
                      <h3 className="text-[16px] font-bold text-[#16191f] leading-snug">
                        {t.passkeyTitle}
                      </h3>
                      <p className="text-[13px] text-[#545b64] mt-1 leading-[20px]">
                        {t.passkeyDesc}
                      </p>
                      <p className="text-[12px] text-[#545b64] mt-2 font-normal leading-[18px]">
                        {t.passkeyNote}
                      </p>
                    </div>
                  </div>
                </div>

                {/* CARD 2: Authenticator app */}
                <div
                  onClick={() => setSelectedOption('authenticator')}
                  className={`rounded-[8px] p-5 border transition-all cursor-pointer select-none ${selectedOption === 'authenticator'
                      ? 'border-[#0073bb] ring-1 ring-[#0073bb] bg-[#f2f8fd]'
                      : 'border-[#d5dbdb] hover:border-[#879596] bg-white'
                    }`}
                >
                  <div className="flex items-start gap-4">
                    <div className="pt-0.5 shrink-0">
                      <div
                        className={`w-[18px] h-[18px] rounded-full transition-colors flex items-center justify-center ${selectedOption === 'authenticator'
                            ? 'border-[5px] border-[#0073bb] bg-white'
                            : 'border border-[#879596] bg-white'
                          }`}
                      />
                    </div>

                    <AuthenticatorAppIllustration />

                    <div className="flex-1 min-w-0">
                      <h3 className="text-[16px] font-bold text-[#16191f] leading-snug">
                        {t.authenticatorTitle}
                      </h3>
                      <p className="text-[13px] text-[#545b64] mt-1 leading-[20px]">
                        {t.authenticatorDesc}
                      </p>
                    </div>
                  </div>
                </div>

                {/* CARD 3: SMS Verification */}
                <div
                  onClick={() => setSelectedOption('sms')}
                  className={`rounded-[8px] p-5 border transition-all cursor-pointer select-none ${selectedOption === 'sms'
                      ? 'border-[#0073bb] ring-1 ring-[#0073bb] bg-[#f2f8fd]'
                      : 'border-[#d5dbdb] hover:border-[#879596] bg-white'
                    }`}
                >
                  <div className="flex items-start gap-4">
                    <div className="pt-0.5 shrink-0">
                      <div
                        className={`w-[18px] h-[18px] rounded-full transition-colors flex items-center justify-center ${selectedOption === 'sms'
                            ? 'border-[5px] border-[#0073bb] bg-white'
                            : 'border border-[#879596] bg-white'
                          }`}
                      />
                    </div>

                    <PhoneSmsIllustration />

                    <div className="flex-1 min-w-0">
                      <h3 className="text-[16px] font-bold text-[#16191f] leading-snug">
                        {t.smsTitle}
                      </h3>
                      <p className="text-[13px] text-[#545b64] mt-1 leading-[20px]">
                        {t.smsDesc(userPhone)}
                      </p>
                    </div>
                  </div>
                </div>

                {/* CARD 4: Email Verification */}
                <div
                  onClick={() => setSelectedOption('email')}
                  className={`rounded-[8px] p-5 border transition-all cursor-pointer select-none ${selectedOption === 'email'
                      ? 'border-[#0073bb] ring-1 ring-[#0073bb] bg-[#f2f8fd]'
                      : 'border-[#d5dbdb] hover:border-[#879596] bg-white'
                    }`}
                >
                  <div className="flex items-start gap-4">
                    <div className="pt-0.5 shrink-0">
                      <div
                        className={`w-[18px] h-[18px] rounded-full transition-colors flex items-center justify-center ${selectedOption === 'email'
                            ? 'border-[5px] border-[#0073bb] bg-white'
                            : 'border border-[#879596] bg-white'
                          }`}
                      />
                    </div>

                    <EmailIllustration />

                    <div className="flex-1 min-w-0">
                      <h3 className="text-[16px] font-bold text-[#16191f] leading-snug">
                        {t.emailTitle}
                      </h3>
                      <p className="text-[13px] text-[#545b64] mt-1 leading-[20px]">
                        {t.emailDesc(userEmail)}
                      </p>
                    </div>
                  </div>
                </div>

              </div>

              {/* Pill Action Buttons */}
              <div className="flex items-center justify-end gap-3 pt-6 border-t border-[#eaeded]">
                <button
                  type="button"
                  onClick={handleSkip}
                  className="h-[36px] px-6 rounded-full border border-[#0073bb] text-[#0073bb] hover:bg-[#f2f8fd] text-[14px] font-bold transition-colors cursor-pointer"
                >
                  {t.skipForNow}
                </button>

                <button
                  type="button"
                  onClick={handleNextFromStep1}
                  disabled={isVerifying}
                  className="h-[36px] px-6 rounded-full bg-[#0073bb] hover:bg-[#005f9e] disabled:opacity-50 text-white text-[14px] font-bold transition-colors cursor-pointer flex items-center gap-2"
                >
                  {isVerifying ? (
                    <>
                      <Loader2 className="w-4 h-4 animate-spin text-white" />
                      <span>{t.registering}</span>
                    </>
                  ) : (
                    <span>{t.next}</span>
                  )}
                </button>
              </div>
            </>
          ) : (
            /* ═══════════════ STEP 2: CONFIGURE & VERIFY MFA ═══════════════ */
            <>
              {/* Title */}
              <h1 className="text-[24px] font-normal text-[#16191f] tracking-tight mb-2">
                {selectedOption === 'authenticator'
                  ? t.step2AuthTitle
                  : selectedOption === 'sms'
                    ? t.step2SmsTitle
                    : t.step2EmailTitle}
              </h1>
              <p className="text-[14px] text-[#545b64] mb-6">
                {t.step2Subtitle} <strong className="text-[#16191f]">{deviceName}</strong>
              </p>

              {/* Authenticator App Step-by-Step Flow */}
              {selectedOption === 'authenticator' && (
                <div className="space-y-6">
                  {/* Step 1: Supported Apps */}
                  <div className="p-4 rounded-[8px] bg-[#f8f9fa] border border-[#d5dbdb]">
                    <h3 className="text-[14px] font-bold text-[#16191f] mb-2">
                      {t.step1Apps}
                    </h3>
                    <p className="text-[13px] text-[#545b64] mb-3">
                      {t.step1AppsDesc}
                    </p>
                    <div className="flex flex-wrap items-center gap-3">
                      <div className="flex items-center gap-1.5 px-3 py-1.5 rounded-[6px] bg-white border border-[#d5dbdb] text-[13px] font-medium text-[#16191f]">
                        <SiGoogleauthenticator className="text-[#EA4335] text-base" />
                        <span>Google Authenticator</span>
                      </div>
                      <div className="flex items-center gap-1.5 px-3 py-1.5 rounded-[6px] bg-white border border-[#d5dbdb] text-[13px] font-medium text-[#16191f]">
                        <FaMicrosoft className="text-[#00A4EF] text-sm" />
                        <span>Microsoft Authenticator</span>
                      </div>
                      <div className="flex items-center gap-1.5 px-3 py-1.5 rounded-[6px] bg-white border border-[#d5dbdb] text-[13px] font-medium text-[#16191f]">
                        <SiIcloud className="text-[#369EEF] text-base" />
                        <span>Apple Passwords</span>
                      </div>
                    </div>
                  </div>

                  {/* Step 2: QR Code Scan */}
                  <div className="p-4 rounded-[8px] bg-[#f8f9fa] border border-[#d5dbdb]">
                    <h3 className="text-[14px] font-bold text-[#16191f] mb-2">
                      {t.step2Scan}
                    </h3>
                    <p className="text-[13px] text-[#545b64] mb-4">
                      {t.step2ScanDesc}
                    </p>

                    <div className="flex flex-col sm:flex-row items-center gap-6">
                      <div className="w-[140px] h-[140px] bg-white p-2.5 rounded-[8px] shrink-0 flex items-center justify-center border border-[#d5dbdb] shadow-xs">
                        {isLoading ? (
                          <Loader2 className="w-6 h-6 animate-spin text-[#0073bb]" />
                        ) : (
                          <QRCode
                            value={
                              qrCodeUri ||
                              `otpauth://totp/Ekaze:${encodeURIComponent(userEmail)}?secret=${secret.replace(/[^A-Za-z0-9]/g, '').toUpperCase()}&issuer=Ekaze&algorithm=SHA1&digits=6&period=30`
                            }
                            size={120}
                            bordered={false}
                            errorLevel="M"
                          />
                        )}
                      </div>

                      <div className="flex-1 space-y-2 text-left">
                        <span className="text-[12px] text-[#545b64] block">{t.secretKeyLabel}</span>
                        <div className="flex items-center gap-2">
                          <code className="text-[14px] font-mono font-bold bg-white px-3 py-1.5 rounded border border-[#d5dbdb] text-[#16191f] tracking-widest select-all">
                            {secret || 'GENERATING-KEY...'}
                          </code>
                          <button
                            type="button"
                            onClick={handleCopySecret}
                            className="h-[34px] px-3 text-[13px] font-bold text-[#16191f] bg-white hover:bg-slate-50 border border-[#d5dbdb] rounded-[4px] transition-colors cursor-pointer flex items-center gap-1.5"
                          >
                            {copied ? (
                              <>
                                <Check className="w-3.5 h-3.5 text-emerald-600" />
                                <span>{t.copied}</span>
                              </>
                            ) : (
                              <>
                                <Copy className="w-3.5 h-3.5" />
                                <span>{t.copy}</span>
                              </>
                            )}
                          </button>
                        </div>
                        <p className="text-[12px] text-[#545b64] pt-1">
                          {t.spacesIgnored}
                        </p>
                      </div>
                    </div>
                  </div>

                  {/* Step 3: Enter Code */}
                  <div className="p-4 rounded-[8px] bg-[#f8f9fa] border border-[#d5dbdb]">
                    <h3 className="text-[14px] font-bold text-[#16191f] mb-1">
                      {t.step3Code}
                    </h3>
                    <p className="text-[13px] text-[#545b64] mb-3">
                      {t.step3CodeDesc}
                    </p>
                    <SixDigitPinInput
                      value={code}
                      onChange={(val) => setCode(val)}
                    />
                  </div>
                </div>
              )}

              {/* SMS Flow */}
              {selectedOption === 'sms' && (
                <div className="space-y-5">
                  <div className="p-5 rounded-[8px] bg-[#f8f9fa] border border-[#d5dbdb] flex flex-col sm:flex-row sm:items-center justify-between gap-4">
                    <div>
                      <span className="text-[12px] text-[#545b64] block">{t.verifiedPhone}</span>
                      <span className="text-[15px] font-mono font-bold text-[#16191f]">
                        {userPhone}
                      </span>
                    </div>
                    <button
                      type="button"
                      onClick={handleSendCode}
                      className="h-[36px] px-5 rounded-full bg-[#0073bb] hover:bg-[#005f9e] text-white text-[13px] font-bold transition-colors cursor-pointer"
                    >
                      {codeSent ? t.resendSms : t.sendSms}
                    </button>
                  </div>

                  <div className="p-5 rounded-[8px] bg-[#f8f9fa] border border-[#d5dbdb]">
                    <label className="block text-[14px] font-bold text-[#16191f] mb-2">
                      {t.enterSmsCode} <span className="text-red-500">*</span>
                    </label>
                    <SixDigitPinInput
                      value={code}
                      onChange={(val) => setCode(val)}
                    />
                  </div>
                </div>
              )}

              {/* Email Flow */}
              {selectedOption === 'email' && (
                <div className="space-y-5">
                  <div className="p-5 rounded-[8px] bg-[#f8f9fa] border border-[#d5dbdb] flex flex-col sm:flex-row sm:items-center justify-between gap-4">
                    <div>
                      <span className="text-[12px] text-[#545b64] block">{t.registeredEmail}</span>
                      <span className="text-[15px] font-mono font-bold text-[#16191f]">
                        {userEmail}
                      </span>
                    </div>
                    <button
                      type="button"
                      onClick={handleSendCode}
                      className="h-[36px] px-5 rounded-full bg-[#0073bb] hover:bg-[#005f9e] text-white text-[13px] font-bold transition-colors cursor-pointer"
                    >
                      {codeSent ? t.resendEmail : t.sendEmail}
                    </button>
                  </div>

                  <div className="p-5 rounded-[8px] bg-[#f8f9fa] border border-[#d5dbdb]">
                    <label className="block text-[14px] font-bold text-[#16191f] mb-2">
                      {t.enterEmailCode} <span className="text-red-500">*</span>
                    </label>
                    <SixDigitPinInput
                      value={code}
                      onChange={(val) => setCode(val)}
                    />
                  </div>
                </div>
              )}

              {/* Bottom Buttons for Step 2 */}
              <div className="flex items-center justify-end gap-3 pt-6 border-t border-[#eaeded] mt-6">
                <button
                  type="button"
                  onClick={() => setStep(1)}
                  className="h-[36px] px-6 rounded-full border border-[#0073bb] text-[#0073bb] hover:bg-[#f2f8fd] text-[14px] font-bold transition-colors cursor-pointer"
                >
                  {t.previous}
                </button>

                <button
                  type="button"
                  onClick={handleVerifyStep2}
                  disabled={code.length !== 6 || isVerifying}
                  className="h-[36px] px-6 rounded-full bg-[#0073bb] hover:bg-[#005f9e] disabled:opacity-40 disabled:cursor-not-allowed text-white text-[14px] font-bold transition-colors cursor-pointer flex items-center gap-2"
                >
                  {isVerifying ? (
                    <>
                      <Loader2 className="w-4 h-4 animate-spin text-white" />
                      <span>{t.registering}</span>
                    </>
                  ) : (
                    <span>{t.registerMfa}</span>
                  )}
                </button>
              </div>
            </>
          )}

        </div>
      </main>

      {/* Footer Copyright */}
      <footer className="relative z-10 w-full text-center text-[12px] text-[#545b64] py-6 select-none">
        {t.footer}
      </footer>
    </div>
  );
};

export default MfaSetupPage;
